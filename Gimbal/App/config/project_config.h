#define PROJECT_DRIVE_VELOCITY_KD (0.0F)
#define PROJECT_STEERING_POSITION_KP (8.0F)
#define PROJECT_STEERING_POSITION_KI (0.0F)
#define PROJECT_STEERING_POSITION_KD (0.0F)
#define PROJECT_STEERING_VELOCITY_KP (0.5F)
#define PROJECT_STEERING_VELOCITY_KI (0.0F)
#define PROJECT_STEERING_VELOCITY_KD (0.0F)
#define PROJECT_YAW_POSITION_KP (8.0F)
#define PROJECT_YAW_POSITION_KI (0.0F)
#define PROJECT_YAW_POSITION_KD (0.0F)
#define PROJECT_YAW_VELOCITY_KP (0.5F)
#define PROJECT_YAW_VELOCITY_KI (0.0F)
#define PROJECT_YAW_VELOCITY_KD (0.0F)

/* 安全与遥控。 */
#define PROJECT_DR16_OFFLINE_TIMEOUT_MS (100U)
#define PROJECT_SAFETY_DISCONNECTION_MS (500U)

#if (PROJECT_DR16_LOCATION != APP_DEVICE_LOCATION_GIMBAL) &&                              \
    (PROJECT_DR16_LOCATION != APP_DEVICE_LOCATION_CHASSIS)
#error "PROJECT_DR16_LOCATION must select the gimbal or chassis board"
#endif

#if (PROJECT_FEEDER_LOCATION != APP_DEVICE_LOCATION_GIMBAL) &&                            \
    (PROJECT_FEEDER_LOCATION != APP_DEVICE_LOCATION_CHASSIS)
#error "PROJECT_FEEDER_LOCATION must select the gimbal or chassis board"
#endif

#if (PROJECT_GIMBAL_COMM_TX_BASE_ID <= 0x20FU) ||                                  \
    (PROJECT_CHASSIS_COMM_TX_BASE_ID <= 0x20FU)
#error "Board communication identifiers must not overlap DJI motor identifiers"
#endif

#endif
