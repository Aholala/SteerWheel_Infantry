#endif
#define PROJECT_BOARD_COMM_TX_TIMEOUT_MS (2U)
#define PROJECT_BOARD_COMM_OFFLINE_MS (100U)

/* 云台：Pitch DM4310 / CAN1，Yaw GM6020 / CAN2。 */
#define PROJECT_PITCH_DM4310_COMMAND_ID (0x01U)
#define PROJECT_PITCH_DM4310_FEEDBACK_ID (0x11U)
#define PROJECT_YAW_GM6020_ID (1U)
#define PROJECT_YAW_GM6020_ENCODER_ZERO (0U)

/* 底盘：四个 M3508 / CAN1，四个 GM6020 / CAN3。 */
#define PROJECT_CHASSIS_MODULE_COUNT (4U)
#define PROJECT_DRIVE_FRONT_LEFT_ID (1U)
#define PROJECT_DRIVE_FRONT_RIGHT_ID (2U)
#define PROJECT_DRIVE_REAR_LEFT_ID (3U)
#define PROJECT_DRIVE_REAR_RIGHT_ID (4U)
#define PROJECT_STEERING_FRONT_LEFT_ID (1U)
#define PROJECT_STEERING_FRONT_RIGHT_ID (2U)
#define PROJECT_STEERING_REAR_LEFT_ID (3U)
#define PROJECT_STEERING_REAR_RIGHT_ID (4U)

/* 发射：两摩擦轮固定在云台板，拨弹盘位置由 PROJECT_FEEDER_LOCATION 选择。 */
#define PROJECT_FRICTION_LEFT_ID (5U)
#define PROJECT_FRICTION_RIGHT_ID (6U)
#define PROJECT_FEEDER_ID (7U)

/* 电机公共参数。零位和方向必须按实车标定后修改。 */
#define PROJECT_MOTOR_FEEDBACK_TIMEOUT_MS (50U)
#define PROJECT_DJI_CURRENT_SCALE_A_PER_COUNT (0.00061035F)
#define PROJECT_DJI_MAXIMUM_TEMPERATURE_C (80.0F)
#define PROJECT_MOTOR_DIRECTION_FORWARD (1.0F)
#define PROJECT_MOTOR_DIRECTION_REVERSE (-1.0F)

/* 舵轮几何。当前值是安全占位，不代表实车尺寸。 */
#define PROJECT_CHASSIS_HALF_WHEELBASE_M (0.25F)
#define PROJECT_CHASSIS_HALF_TRACK_M (0.25F)
#define PROJECT_CHASSIS_WHEEL_RADIUS_M (0.076F)
#define PROJECT_CHASSIS_DRIVE_REDUCTION_RATIO (19.2032F)
#define PROJECT_CHASSIS_MAX_WHEEL_VELOCITY_M_PER_S (4.0F)

/* 云台范围。 */
#define PROJECT_GIMBAL_PITCH_MIN_RAD (-0.50F)
#define PROJECT_GIMBAL_PITCH_MAX_RAD (0.45F)
#define PROJECT_GIMBAL_TARGET_TOLERANCE_RAD (0.01F)

/* PID 初值仅用于建立可运行框架，上车前必须通过 Ozone 调整。 */
#define PROJECT_PID_DERIVATIVE_FILTER_HZ (50.0F)
#define PROJECT_PID_INTEGRAL_LIMIT (5.0F)
#define PROJECT_PID_CURRENT_OUTPUT_LIMIT_A (8.0F)
